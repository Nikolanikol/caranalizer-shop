import { notFound } from "next/navigation";
import { isShopLocale } from "@/lib/shop/urls";

/**
 * Раздел запчастей.
 *
 * Своей навигации у раздела нет. Прилипающая полоса «Запчасти | Каталог» отсюда убрана:
 * она появилась ради кнопки корзины, а та переехала в шапку сайта. После переезда в полосе
 * остались дубль пункта «Запчасти» из шапки и одна ссылка на каталог — за 48 пикселей
 * на каждой из 1216 страниц раздела и второй прилипающий слой под шапкой.
 *
 * Корзина живёт в `[lang]/layout.tsx`: её кнопка в шапке, а шапка выше по дереву,
 * и контекст оттуда был недоступен.
 *
 * Языков у раздела два — `ru` и `en`, список в `SHOP_LOCALES`. До 27.08.2026 был один:
 * считалось, что иноязычный покупатель обслуживается на kmotors. Выгрузка Search Console
 * это опровергла — половина кликов приходила на `/en/` и `/ar/`, а kmotors торгует новыми
 * деталями, и б/у покупателю там нечего купить.
 *
 * На языках вне списка раздела по-прежнему не существует: 404, а не пустая оболочка.
 * Пустая оболочка с русским каталогом внутри — это дубль, который Google склеит
 * с оригиналом, а покупателю не поможет.
 */
export default async function ShopLayout({
  children,
  params,
}: {
  children: React.ReactNode;
  params: Promise<{ lang: string }>;
}) {
  const { lang } = await params;
  if (!isShopLocale(lang)) notFound();

  return <>{children}</>;
}
