'use client';

import { useEffect } from 'react';
import { trackViewItem } from '@/lib/analytics';

/**
 * `view_item` для страницы диска.
 *
 * Отдельным компонентом, потому что страница диска серверная, а событие обязано уйти
 * из браузера. У запчастей то же событие живёт в `offer-picker.tsx` — там есть куда
 * его повесить, поскольку экземпляр выбирают на клиенте. У диска экземпляр один,
 * выбирать нечего, и без этого компонента воронка раздела ломалась бы на первом шаге:
 * `add_to_cart` уходил бы без предшествующего `view_item`, и отчёт GA считал бы
 * конверсию от нуля просмотров.
 *
 * `oem` пустой намеренно: партномера у диска нет. Категория совпадает с сегментом
 * адреса, чтобы в отчёте диски отделялись от запчастей.
 */
export function WheelViewTracker({ id }: { id: string }) {
  useEffect(() => {
    trackViewItem({ id, oem: '', category: 'diski' });
  }, [id]);

  return null;
}
