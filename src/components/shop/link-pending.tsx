'use client';

import React from 'react';
import { createPortal } from 'react-dom';
import { useLinkStatus } from 'next/link';

/**
 * Отклик на клик по ссылке фильтра, сортировки или страницы.
 *
 * Зачем вообще: `loading.tsx` **не срабатывает, когда меняются только параметры запроса**
 * — замерено на чистом Next 16.2.9 (смена сегмента пути даёт скелет сразу, смена `?brand=`
 * не даёт вовсе). А на витрине параметрами живёт всё: сторона, расположение, сортировка,
 * страница, марка и модель. То есть половина кликов по фильтру не показывала ничего.
 *
 * `useLinkStatus` закрывает первую половину перехода — от клика до смены адреса, — и делает
 * это без единого запроса: `pending` встаёт примерно через 50 мс после клика и на мёртвой
 * сети тоже. Вторую половину, от смены адреса до прихода выдачи, закрывает `<Suspense>`
 * в `catalog-view.tsx`. Порознь они дырявые, вместе покрывают переход целиком.
 *
 * Компонент обязан быть потомком `<Link>` — иначе хук всегда вернёт `{ pending: false }`.
 * `Link` из `@/i18n/navigation` подходит: под ним настоящий `next/link` (см. `BaseLink`
 * в next-intl), контекст доходит.
 *
 * Разметку не двигает: заливка `absolute`, полоса `fixed`. Задержка перед появлением —
 * в CSS, а не здесь: на прогретом переходе `pending` живёт десятки миллисекунд, и без
 * неё индикатор моргал бы на каждом клике.
 */
export function LinkPending() {
  const { pending } = useLinkStatus();
  if (!pending) return null;

  return (
    <>
      {/* Заливка самой опции: видно, по какой именно нажали. Родителю нужны
          `relative` и `overflow-hidden`. */}
      <span aria-hidden className="nav-pending-fill" />
      {/*
        Полоса вверху окна — через портал в body, а не на месте. Фильтр стоит
        в `lg:sticky` колонке с `overflow-y-auto` у списка марок: `position: fixed`
        оттуда формально не обрезается, но одного `transform` у любого предка хватит,
        чтобы полоса уехала внутрь колонки. Портал снимает вопрос целиком.
      */}
      {typeof document !== 'undefined' && createPortal(<span aria-hidden className="nav-pending-bar" />, document.body)}
    </>
  );
}
