import { defineRouting } from "next-intl/routing";

export const routing = defineRouting({
  locales: ["ru", "en", "ar"],
  defaultLocale: "ru",

  /**
   * Язык по браузеру не определяем. Это не оптимизация, а исправление бага.
   *
   * По умолчанию next-intl смотрит `accept-language` и cookie, поэтому `/` уводил
   * англоязычный браузер на `/en`, а оттуда middleware отдавал 301 на единственную
   * иноязычную страницу — проверку по VIN. В сумме получалось так:
   *
   *   Accept-Language: en → / → 307 /en → 301 /en/koreancar-vin-check
   *
   * То есть **любой посетитель с нерусским браузером вообще не мог попасть на сайт**:
   * ни на главную, ни в раздел б/у запчастей, который существует только на русском.
   * А браузер с английской локалью при русском владельце — обычное дело.
   *
   * Основной рынок РФ, сайт русский, и многоязычна ровно одна страница. Значит `/`
   * всегда ведёт на `ru`, а на иноязычную версию проверки попадают осознанно —
   * переключателем на самой странице или по прямой ссылке.
   *
   * Cookie заодно не ставим: без определения языка она ни на что не влияет, а лишний
   * cookie на сайте с баннером согласия — это то, о чём пришлось бы отчитываться.
   */
  localeDetection: false,
  localeCookie: false,
});

export type Locale = (typeof routing.locales)[number];
