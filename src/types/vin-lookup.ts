/**
 * Строка журнала проверок по VIN — та, что кабинет показывает человеку.
 *
 * **Не путать с `lib/vin/history.ts`.** Там история в localStorage: она принадлежит
 * браузеру, живёт до очистки хранилища и никуда не уходит. Здесь — журнал на сервере,
 * заведённый ради лимита частоты, и он привязан к аккаунту. Совпадает у них только
 * назначение на экране; источник, срок жизни и правовой статус разные.
 */
export interface VinLookup {
  vin: string;
  /** Что ответил корейский реестр: `found`, `not-found`, `unavailable`, `unknown`. */
  registry: string;
  /** ISO-строка. Формат даты выбирает страница по своей локали. */
  lookedUpAt: string;
}

export interface VinLookupPage {
  items: VinLookup[];
  /** Всего строк у пользователя, а не на странице. */
  total: number;
  page: number;
  pages: number;
}

/**
 * Размер страницы. Лежит здесь, а не в роуте: из `route.ts` Next разрешает
 * экспортировать только обработчики и настройки сегмента, лишний экспорт — ошибка сборки.
 */
export const VIN_HISTORY_PAGE_SIZE = 10;
