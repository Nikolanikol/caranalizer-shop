/**
 * Колёсный диск со skywheel.kr — товар второго донора.
 *
 * Отдельный тип, а не `AutoPart`, и причина не в аккуратности. У детали из partsfit
 * всё держится на партномере: по нему собирается страница артикула и таблица
 * совместимости. У диска партномера нет вовсе — донор его не публикует, — и подбирают
 * диск маркой, моделью авто и диаметром. Натянуть одно на другое значило бы завести
 * товар с пустым ключом в модели, где ключ обязателен.
 *
 * Второе отличие: у детали страница и экземпляр разведены (у одной фары до 64 штук
 * с разных машин). Здесь объявление и есть товар — один комплект, одна цена,
 * свои фотографии.
 *
 * Поля повторяют колонки `skywheel_wheels`. Термины хранятся кодами, а не русским
 * текстом (в отличие от `partsfit_offers`, куда скрапер кладёт русские слова донора):
 * данные донора корейские, русского оригинала нет, и код одинаково честно
 * разворачивается в оба языка.
 */

/** Состояние: как его называет донор полем `휠상태`. Пустое — донор промолчал. */
export type WheelGrade = '' | 'good' | 'fair' | 'repair';

/**
 * Тип диска. Различие не косметическое: `oem` — заводской диск с конкретной машины,
 * `forged` — кованый афтермаркет, `restored` — прошедший восстановление.
 */
export type WheelKind = '' | 'forged' | 'restored' | 'oem' | 'diamond-cut';

/** «1짝» — одно колесо, «1세트» — комплект. Пусто у 106 объявлений из 120. */
export type WheelQuantity = '' | 'set' | 'single';

export interface WheelImage {
  position: number;
  url: string;
}

export interface Wheel {
  id: string;
  slug: string;

  brandSlug: string;
  brandName: string;
  /** Модель авто. Пусто у афтермаркета, который не привязан к одной машине. */
  model: string;
  diameter: number;

  /** Заголовок и описание донора по-корейски. Исходник для закупщика, не для витрины. */
  titleKo: string;
  descriptionKo: string;

  condition: 'new' | 'used';
  grade: WheelGrade;
  wheelKind: WheelKind;
  quantity: WheelQuantity;
  withTyres: boolean;

  /**
   * Цена продажи в вонах, и только она. Рубли и доллары считает `lib/shop/pricing.ts`.
   *
   * `null` — штатное значение, а не сбой разбора: у части объявлений цену продажи
   * назвать нечем (донор публикует только цену со сдачей своих дисков в зачёт либо
   * прайс по диаметрам, в котором нашего нет). Витрина в этом случае пишет
   * «по запросу» и не даёт положить товар в корзину — по этой цене выставляется счёт.
   */
  priceKrw: number | null;

  /**
   * Параметры подбора. Донор их почти не заполняет — PCD у восьми объявлений из ста
   * двадцати, — поэтому пустой массив здесь норма, а не признак ошибки разбора.
   * Строить на них фильтр нельзя: он окажется пустым у семи товаров из восьми.
   */
  widthJ: number[];
  pcd: number[];
  offsetEt: number[];
  boreCb: number | null;
  tyre: string;

  certified: boolean;
  /** Проданное с доски донора не исчезает — он дописывает метку в заголовок. */
  sold: boolean;

  region: string;
  sellerRef: string;
  sourceUrl: string;

  images: WheelImage[];
}
