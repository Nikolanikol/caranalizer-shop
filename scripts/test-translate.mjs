function tr(name, dict) {
  let r = name;
  const keys = Object.keys(dict).sort((a,b) => b.length - a.length);
  for (const k of keys) {
    // For short Korean words (<=2 chars), only match as whole space-separated tokens
    // to prevent partial matches inside compound words
    if (k.length <= 2 && /[가-힯]/.test(k)) {
      r = r.replace(new RegExp('(?<=^|\\s)' + k + '(?=$|\\s)', 'g'), dict[k]);
    } else {
      r = r.replaceAll(k, dict[k]);
    }
  }
  return r.trim();
}

function trEn(name, dict) {
  let r = name;
  const keys = Object.keys(dict).sort((a,b) => b.length - a.length);
  for (const k of keys) {
    const escaped = k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    r = r.replace(new RegExp('\\b' + escaped + '\\b', 'gi'), dict[k]);
  }
  return r;
}

